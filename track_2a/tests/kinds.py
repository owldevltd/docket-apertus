"""The kind of every shipped document from the words of its first page, without a model, against the kind
read by hand (document.json, "kind"); the record with the kind must still fit the contract.

    python3 tests/kinds.py --pages=<analyzed dir> --documents=<records dir> [--out=<file.md>] <document dir> ...
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from docket.config import load_config  # noqa: E402
from docket.pipeline import add_kind, load_contract, load_knowledge  # noqa: E402


def main(argv: list[str]) -> int:
    dirs = [Path(a) for a in argv if not a.startswith("--")]
    pages_dir = next((Path(a[8:]) for a in argv if a.startswith("--pages=")), None)
    records_dir = next((Path(a[12:]) for a in argv if a.startswith("--documents=")), None)
    out_file = next((Path(a[6:]) for a in argv if a.startswith("--out=")), None)
    if not dirs or pages_dir is None or records_dir is None:
        print("usage: python3 tests/kinds.py --pages=<dir> --documents=<dir> [--out=<file.md>] <document dir> ...")
        return 1
    config = load_config()
    contract = load_contract(config)
    knowledge = load_knowledge(config)
    print(f"ok   {len(knowledge.kinds)} kinds in the knowledge")
    rows = []
    same = known = 0
    failed = False
    for d in dirs:
        info = d / "document.json"
        pdf = next(d.glob("*.pdf"), None) if d.is_dir() else None
        if pdf is None or not info.is_file():
            continue
        meta = json.loads(info.read_text(encoding="utf-8"))
        want = (meta.get("kind") or {}).get("value")
        record_file = records_dir / f"{pdf.stem}.json"
        if not record_file.is_file():
            print(f"FAIL {pdf.stem}: no record in {records_dir}")
            failed = True
            continue
        record = json.loads(record_file.read_text(encoding="utf-8"))
        pages = []
        n = 1
        while (pages_dir / f"{pdf.stem}-s{n}.json").is_file():
            pages.append(json.loads((pages_dir / f"{pdf.stem}-s{n}.json").read_text(encoding="utf-8")))
            n += 1
        found = add_kind(record, pages, knowledge)
        got = found["kind"] if found else None
        errors = contract.check(record)
        if errors:
            failed = True
        if want:
            known += 1
            same += 1 if got == want else 0
        mark = "ok  " if got == want else "note"
        why = found["why"] if found else "no words of any kind on the first page"
        state = "valid" if not errors else errors[0]
        print(f"{mark} {pdf.stem}: {got or '-'} against {want or 'none'} ({why}); record {state}")
        rows.append(f"| {pdf.stem} | {want or '—'} | {got or '—'} | {why} | {found['block'] if found else '—'} |")
    print(f"{same} of {known} kinds as read by hand")
    if out_file is not None:
        out_file.parent.mkdir(parents=True, exist_ok=True)
        head = (
            "# The kind of the shipped documents\n\n"
            f"Generated by `tests/kinds.py` on {time.strftime('%Y-%m-%d')}, no model call. The kind from the words "
            "of the first page (headline, section names, type labels, signature block) against the kind read by "
            "hand.\n\n"
            "| Document | By hand | By the rule | Why | Block |\n|---|---|---|---|---|\n"
        )
        out_file.write_text(head + "\n".join(rows) + f"\n\n{same} of {known} as read by hand.\n", encoding="utf-8")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
